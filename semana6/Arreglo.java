package semana6;

public class Arreglo {
    // creacion del arreglo
    public static void main(String[] args) {
        int[] a = { 6, 5, 9, 1, 8, 3, 2 };
        // recorrer a mostrar el arreglo
        for (int i = 0; i < a.length; i++) {
            System.out.println("a[" + i + "]=" + a[i]);
        }
    }

}